def test_migration_creates_every_model_table(engine: Engine) -> None:
    tables = set(inspect(engine).get_table_names())
    assert set(m.Base.metadata.tables) | set(m.ExternalBase.metadata.tables) <= tables


def test_models_and_migrations_are_in_sync(alembic_cfg: Config, engine: Engine) -> None:
    # Raises AutogenerateDiffsDetected if a model changed without a migration.
    command.check(alembic_cfg)


def test_downgrade_to_base_and_back(alembic_cfg: Config, engine: Engine) -> None:
    command.downgrade(alembic_cfg, "base")
    assert "wafers" not in inspect(engine).get_table_names()
    command.upgrade(alembic_cfg, "head")
    assert "wafers" in inspect(engine).get_table_names()


def test_measurement_tables_are_weekly_hypertables(engine: Engine) -> None:
    with engine.connect() as conn:
        rows = conn.execute(
            text(
                "SELECT hypertable_name, column_name, time_interval "
                "FROM timescaledb_information.dimensions "
                # the sensor_daily continuous aggregate keeps its own internal hypertable
                "WHERE hypertable_schema = 'public' ORDER BY hypertable_name"
            )
        ).all()
    assert [(r.hypertable_name, r.column_name, r.time_interval) for r in rows] == [
        ("metrology_measurements", "time", timedelta(days=7)),
        ("tool_sensor_readings", "time", timedelta(days=7)),
    ]


# --------------------------------------------------------------------------- ORM + genealogy


def test_relationships_resolve(db: Session, fab: MiniFab) -> None:
    wafer = db.get(m.Wafer, 2)
    assert wafer is not None
    assert wafer.lot.product.node.name == "28nm"
    assert [c.chamber_code for c in fab.chamber_a.tool.chambers] == ["A", "B"]
    assert [s.step_name for s in fab.route.steps] == ["m1_etch", "m1_cmp"]


def test_split_lot_keeps_parent_link(db: Session, fab: MiniFab) -> None:
    child = m.Lot(
        lot_id=2, lot_code="L26001.2", parent_lot_id=fab.lot.lot_id, product_id=1, route_id=1,
        start_time=at(60), status="active",
    )  # fmt: skip
    db.add(child)
    db.flush()
    db.add(m.LotEvent(lot_id=1, event_type="split", event_time=at(60), related_lot_id=2))
    fab.wafers[2].lot_id = 2
    db.flush()
    db.refresh(child)
    assert child.parent is fab.lot
    assert [w.wafer_id for w in child.wafers] == [3]


def test_commonality_query_finds_wafers_by_chamber_and_window(db: Session, fab: MiniFab) -> None:
    # Wafers 1 and 3 run in chamber A, wafer 2 in chamber B.
    for wafer, chamber, start in [(1, 1, 0), (2, 2, 0), (3, 1, 200)]:
        db.add(
            m.WaferStepHistory(
                wafer_id=wafer, route_step_id=1, lot_id=1, chamber_id=chamber, recipe_id=1,
                track_in=at(start), track_out=at(start + 20),
            )
        )  # fmt: skip
    db.flush()
    hit = db.scalars(
        select(m.WaferStepHistory.wafer_id)
        .where(m.WaferStepHistory.chamber_id == 1)
        .where(m.WaferStepHistory.track_in.between(T0, at(100)))
    ).all()
    assert hit == [1]


def test_rework_is_a_second_pass_not_a_duplicate(db: Session, fab: MiniFab) -> None:
    for pass_no in (1, 2):
        db.add(
            m.WaferStepHistory(
                wafer_id=1, route_step_id=1, pass_no=pass_no, lot_id=1, chamber_id=1,
                recipe_id=1, track_in=at(pass_no * 60), track_out=at(pass_no * 60 + 20),
            )
        )  # fmt: skip
    db.flush()
    assert len(db.get_one(m.Wafer, 1).history) == 2


