@pytest.mark.parametrize("case", VIOLATIONS)
def test_database_rejects_invalid_rows(db: Session, fab: MiniFab, case: str) -> None:
    db.add(VIOLATIONS[case](fab))
    with pytest.raises(DBAPIError):
        db.flush()


def test_database_rejects_one_dimensional_wafer_map(db: Session, fab: MiniFab) -> None:
    # Raw SQL on purpose: the ORM rejects a 1-D list before it reaches Postgres, but the COPY
    # loader bypasses the ORM, so the CHECK constraint itself must hold.
    with pytest.raises(DBAPIError, match="bin_map_is_2d"):
        db.execute(
            text("INSERT INTO wafer_maps (wafer_id, tested_at, bin_map) VALUES (1, now(), :m)"),
            {"m": [1, 1, 2]},
        )
