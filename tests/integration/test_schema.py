def test_hypertable_rows_land_in_weekly_chunks(db: Session, fab: MiniFab) -> None:
    for week in range(3):
        db.add(
            m.ToolSensorReading(
                time=T0 + timedelta(weeks=week), wafer_id=1, route_step_id=1, parameter_id=1,
                chamber_id=1, value=500.0 + week,
            )
        )  # fmt: skip
    db.flush()
    chunks = db.execute(text("SELECT count(*) FROM show_chunks('tool_sensor_readings')"))
    assert chunks.scalar_one() == 3


def test_wafer_map_round_trips_as_2d_array(db: Session, fab: MiniFab) -> None:
    grid = [[0, 1, 1, 0], [1, 2, 1, 1], [1, 1, 3, 1], [0, 1, 1, 0]]
    db.add(m.WaferMap(wafer_id=1, tested_at=at(500), bin_map=grid))
    db.flush()
    db.expire_all()
    assert db.get_one(m.WaferMap, 1).bin_map == grid


def test_wafer_yield_uses_pass_bins(db: Session, fab: MiniFab) -> None:
    db.add_all(
        [
            m.WaferBinSummary(wafer_id=1, bin_code=1, die_count=72),
            m.WaferBinSummary(wafer_id=1, bin_code=2, die_count=5),
            m.WaferBinSummary(wafer_id=1, bin_code=3, die_count=3),
            m.WaferBinSummary(wafer_id=2, bin_code=2, die_count=80),
        ]
    )
    db.flush()
    db.execute(text("REFRESH MATERIALIZED VIEW wafer_yield"))
    rows = db.execute(
        text("SELECT wafer_id, tested_dies, good_dies, yield_pct FROM wafer_yield ORDER BY 1")
    ).all()
    assert [tuple(r) for r in rows] == [(1, 80, 72, 90), (2, 80, 0, 0)]


